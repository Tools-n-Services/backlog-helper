-- Очередь писем об ответах в обсуждении (FR-302, FR-307).
--
-- Тот же приём, что и со сменой статуса: событие уже существует строкой,
-- и очередь берётся из неё, а не из отдельной таблицы задач. Комментарий
-- с notified_at is null — это письмо, которое ещё не ушло.
--
-- Почему не отправлять прямо при создании комментария: почта ненадёжна,
-- а комментарий важнее письма о нём. Упавший почтовый сервис не должен
-- откатывать сам комментарий.
ALTER TABLE "comment" ADD COLUMN "notified_at" TIMESTAMPTZ(6);

-- Частичный: разбирать нужно только неразосланные, а их единицы на фоне
-- всей истории обсуждений.
CREATE INDEX "comment_pending_notification_idx" ON "comment" ("created_at")
  WHERE "notified_at" IS NULL AND "deleted_at" IS NULL AND NOT "internal";
