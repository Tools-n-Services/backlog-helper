-- Расширения. Идут первой миграцией, потому что от них зависят типы колонок
-- в следующей: app_user.email объявлен как citext.
--
-- pgcrypto нужен не везде — в PostgreSQL 13+ gen_random_uuid() встроен, —
-- но ставится явно: форк может встать на управляемый Postgres, где версия
-- окажется старше, и молчаливое отсутствие функции по умолчанию проявится
-- только при первой вставке.

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Регистронезависимый email: adm@x.ru и ADM@x.ru — один человек, и это
-- должно гарантироваться уникальным индексом, а не приведением в коде.
CREATE EXTENSION IF NOT EXISTS "citext";

-- Поиск похожих обращений по опечаткам и частичным совпадениям (FR-122).
CREATE EXTENSION IF NOT EXISTS "pg_trgm";
